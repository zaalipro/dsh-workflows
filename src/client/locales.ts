export type WorkflowsLocale = typeof workflowLocales.en | typeof workflowLocales.zh

export type ClientStatusLabelKey =
  | 'running' | 'pausing' | 'stopping' | 'needs-input' | 'paused'
  | 'budget-limited' | 'completed' | 'failed' | 'cancelled' | 'interrupted'

/** Pick the registered dictionary that matches a bound translator (or English). */
export function workflowLocaleFromBind(translate: ((key: string) => unknown) | undefined): WorkflowsLocale {
  if (typeof translate !== 'function') return workflowLocales.en
  try {
    return String(translate('title')) === workflowLocales.zh.title
      ? workflowLocales.zh
      : workflowLocales.en
  } catch {
    return workflowLocales.en
  }
}

export function workflowChatLabelsFromLocale(locale: WorkflowsLocale) {
  const status = {
    running: locale.chatRunning,
    completed: locale.chatCompleted,
    failed: locale.chatFailed,
    cancelled: locale.chatCancelled,
    interrupted: locale.chatInterrupted,
  } as const
  return {
    noMembers: locale.chatNoMembers,
    unphased: locale.chatUnphased,
    emptyPhase: locale.chatEmptyPhase,
    emptyMember: locale.chatEmptyMember,
    childUnavailable: locale.chatChildUnavailable,
    childFailed: locale.chatChildFailed,
    inspect: (count: number) => count === 1 ? locale.chatInspectOne : locale.chatInspectMany(count),
    status,
    statusCount: (key: keyof typeof status, count: number) => `${status[key]} ${count}`,
    openMember: locale.chatOpenMember,
  }
}

